// Isolated offline browser verification. No real AI, search, or voice calls.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const assert = require("node:assert/strict");
const path = require("node:path");
const fs = require("node:fs/promises");

async function main() {
  const baseURL = process.env.INTERVIEW_TEST_URL || "http://127.0.0.1:8003";
  assert.equal((await (await fetch(`${baseURL}/api/health`)).json()).ai_mode, "demo");
  const browser = await chromium.launch({headless: true, executablePath: process.env.BROWSER_EXECUTABLE || undefined});
  const page = await browser.newPage({viewport: {width: 1000, height: 1000}});
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const writes = []; page.on("request", request => { if (request.method() === "POST") writes.push(new URL(request.url()).pathname); });
  const read = async id => (await fetch(`${baseURL}/api/interviews/${id}`)).json();
  try {
    await page.goto(baseURL);
    await page.getByText("当前为离线演示：", {exact:false}).waitFor();
    await page.locator("#resume").setInputFiles(path.resolve("examples/sample_resume.docx"));
    await page.locator("#company").fill("专项复练验收公司");
    await page.locator("#position").fill("技术岗位");
    await page.getByRole("button", {name:"准备并开始面试", exact:true}).click();
    await page.getByText("面试官（第 1 轮）：", {exact:false}).waitFor();
    const sourceId = new URL(page.url()).searchParams.get("session");
    await page.locator("#answer").fill("我负责 PCAP 数据清洗和 Suricata 规则验证，其他成员负责模型架构。");
    await page.getByRole("button", {name:"提交回答", exact:true}).click();
    await page.getByText("面试官（第 2 轮）：", {exact:false}).waitFor();
    await page.getByRole("button", {name:"结束面试并生成报告", exact:true}).click();
    await page.getByRole("heading", {name:"面试复盘报告", exact:true}).waitFor();
    const source = await read(sourceId); writes.length = 0;
    await page.getByRole("button", {name:"按本轮计划开始专项练习", exact:true}).click();
    await page.locator("#training-plan-status").waitFor({state:"visible"});
    await page.getByRole("button", {name:"提交并查看讲评", exact:true}).waitFor();
    const trainingId = new URL(page.url()).searchParams.get("session");
    const initial = await read(trainingId);
    assert.notEqual(trainingId, sourceId);
    assert.equal(initial.mode, "training");
    assert.equal(initial.resume_id, source.resume_id);
    assert.equal(initial.research_origin, "reused");
    assert.equal(initial.turns.length, 1);
    assert.ok(initial.turns[0].question.includes(source.report.next_practice.focus));
    assert.ok(!writes.some(url=>url.startsWith("/api/resumes")));
    await page.locator("#answer").fill("我本人负责 Suricata 规则验证，通过真实样本检查规则的误报。");
    await page.getByRole("button", {name:"提交并查看讲评", exact:true}).click();
    await page.getByRole("heading", {name:"第 1 题讲评", exact:true}).waitFor();
    await page.locator("#training-controls").waitFor({state:"visible"});
    assert.ok(await page.locator("#answer-form").isHidden());
    await page.reload();
    await page.getByRole("heading", {name:"第 1 题讲评", exact:true}).waitFor();
    await page.getByRole("button", {name:"重答本题", exact:true}).click();
    await page.getByText("这是第 1 题的重答", {exact:false}).waitFor();
    const repeated = await read(trainingId);
    assert.equal(repeated.turns[1].question, repeated.turns[0].question);
    assert.equal(repeated.turns[1].answer, null);
    await page.locator("#answer").fill("我负责数据清洗，用实际样本对比规则误报，明确记录每项验证的结果。");
    await page.getByRole("button", {name:"提交并查看讲评", exact:true}).click();
    await page.getByRole("heading", {name:"第 2 题讲评", exact:true}).waitFor();
    await fs.mkdir(path.resolve("data/verification"), {recursive:true});
    await page.locator("#training-controls").scrollIntoViewIfNeeded();
    await page.screenshot({path:path.resolve("data/verification/training_feedback.png")});
    await page.getByRole("button", {name:"继续下一题", exact:true}).click();
    await page.getByText("面试官（第 3 轮）：", {exact:false}).waitFor();
    assert.ok(await page.locator("#training-controls").isHidden());
    await page.getByRole("button", {name:"结束面试并生成报告", exact:true}).click();
    await page.getByRole("heading", {name:"面试复盘报告", exact:true}).waitFor();
    assert.equal((await read(trainingId)).report.answer_reviews.length, 2);
    assert.deepEqual(await read(sourceId), source);
    await page.getByRole("button", {name:"历史面试", exact:true}).click();
    await page.locator(`[data-session-id="${trainingId}"]`).getByRole("button", {name:"复用设置和资料"}).click();
    await page.locator("#preparation-detail").waitFor({state:"visible"});
    assert.equal(await page.locator("#practice-mode").inputValue(), "training");
    assert.equal(await page.locator("#training-focus").inputValue(), initial.training_plan.focus);
    assert.equal(await page.locator("#duration").inputValue(), String(initial.duration_target / 60));
    await page.locator("#practice-mode").selectOption("training");
    await page.locator("#training-focus").fill("TLS握手与验证方法");
    await page.locator("#resume").setInputFiles(path.resolve("examples/sample_resume.docx"));
    await page.locator("#company").fill("专项复练验收公司");
    await page.locator("#position").fill("技术岗位");
    await page.getByRole("button", {name:"准备并开始面试", exact:true}).click();
    await page.getByText("TLS握手与验证方法", {exact:false}).first().waitFor();
    await page.getByRole("button", {name:"提交并查看讲评", exact:true}).waitFor();
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({result:"passed", mode:"offline", checked:["one_click_practice", "reuse_without_upload", "focused_opening", "feedback_pause", "reload", "repeat", "continue", "training_report", "source_unchanged", "restore_training_settings", "manual_training"]}));
  } finally { await browser.close(); }
}
main().catch(error=>{console.error(error);process.exitCode=1;});
